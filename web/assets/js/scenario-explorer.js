/* =====================================================================
   SCENARIO EXPLORER — render, search, filter, and detail drawer logic.
   Data comes from usecases.json, generated by usecases/_framework/usecases.sh.
   ===================================================================== */
(function () {
  "use strict";

  var REPO_TREE = "https://github.com/microsoft/frontier-sre-agent-rvas/tree/main/";
  var TRIGGER_LABELS = { schedule: "Scheduled", chat: "On-demand", alert: "Event-driven" };
  var AUTONOMY_LABELS = { "read-only": "Read-only", approval: "Needs approval", autonomous: "Autonomous" };
  var STATUS_LABELS = { idea: "Idea", draft: "Draft", built: "Built", validated: "Validated" };
  var COMPONENT_LABELS = [
    ["skill", "Skill"], ["subagent", "Subagent"], ["tool", "Tool"], ["task", "Scheduled task"],
    ["permissions", "Permission script"], ["tests", "Tests"], ["sampleReport", "Sample report"]
  ];

  var grid = document.getElementById("scenario-grid");
  var emptyState = document.getElementById("scenario-empty");
  var resultsCount = document.getElementById("scenario-results-count");
  var searchInput = document.getElementById("scenario-search-input");
  var triggerFilter = document.getElementById("scenario-trigger-filter");
  var autonomyFilter = document.getElementById("scenario-autonomy-filter");
  var statusFilter = document.getElementById("scenario-status-filter");
  var topPickToggle = document.getElementById("scenario-toppick-toggle");
  var chipsContainer = document.getElementById("scenario-category-chips");

  if (!grid) return;

  var SCENARIOS = [];
  var categoryBySlug = {};
  var state = { query: "", category: "", trigger: "", autonomy: "", status: "", topPickOnly: false };

  function showError(message) {
    grid.innerHTML = "";
    emptyState.textContent = message;
    emptyState.hidden = false;
    resultsCount.textContent = "";
  }

  fetch("usecases.json", { cache: "no-cache" })
    .then(function (r) {
      if (!r.ok) throw new Error("HTTP " + r.status);
      return r.json();
    })
    .then(init)
    .catch(function () {
      showError("The use case list could not be loaded. Try again later.");
    });

  function setText(id, value) {
    var el = document.getElementById(id);
    if (el) el.textContent = value;
  }

  function fillOptions(select, values, labels) {
    var wrap = select.closest(".scenario-select-wrap") || select;
    if (!values.length) { wrap.hidden = true; return; }
    values.forEach(function (v) {
      var o = document.createElement("option");
      o.value = v;
      o.textContent = labels[v] || v;
      select.appendChild(o);
    });
  }

  function init(data) {
    SCENARIOS = data.usecases || [];
    (data.domains || []).forEach(function (c) { categoryBySlug[c.slug] = c; });

    var domainsInUse = (data.domains || []).filter(function (c) {
      return SCENARIOS.some(function (s) { return s.domain === c.slug; });
    });
    var triggers = uniq(flat(SCENARIOS.map(function (s) { return s.trigger || []; })));
    var autonomies = uniq(SCENARIOS.map(function (s) { return s.autonomy; }).filter(Boolean));
    var statuses = ["idea", "draft", "built", "validated"].filter(function (m) {
      return SCENARIOS.some(function (s) { return s.status === m; });
    });

    setText("scenario-count-hero", SCENARIOS.length);
    setText("scenario-lede-count", SCENARIOS.length);
    setText("scenario-stat-total", SCENARIOS.length);
    setText("scenario-stat-domains", domainsInUse.length);
    setText("scenario-stat-quick", SCENARIOS.filter(function (s) { return s.topPick; }).length);
    setText("scenario-stat-triggers", triggers.length);

    domainsInUse.forEach(function (cat) {
      var count = SCENARIOS.filter(function (s) { return s.domain === cat.slug; }).length;
      var btn = document.createElement("button");
      btn.type = "button";
      btn.className = "scenario-chip";
      btn.dataset.category = cat.slug;
      btn.style.setProperty("--card-color", cat.color);
      btn.textContent = cat.label + " (" + count + ")";
      chipsContainer.appendChild(btn);
    });

    fillOptions(triggerFilter, triggers, TRIGGER_LABELS);
    fillOptions(autonomyFilter, autonomies, AUTONOMY_LABELS);
    fillOptions(statusFilter, statuses, STATUS_LABELS);

    bindEvents();
    render();
  }

  function flat(arrays) { return [].concat.apply([], arrays); }
  function uniq(list) {
    return list.filter(function (v, i) { return list.indexOf(v) === i; });
  }

  function timeBadgeClass(timeSaved) {
    var t = (timeSaved || "").toLowerCase();
    if (t === "high") return "scenario-badge-time-high";
    if (t === "medium") return "scenario-badge-time-medium";
    return "scenario-badge-time-low";
  }

  function escapeHtml(str) {
    var div = document.createElement("div");
    div.textContent = str == null ? "" : str;
    return div.innerHTML;
  }

  /* ── Filtering ───────────────────────────────────────────────────── */
  function matches(scenario) {
    if (state.category && scenario.domain !== state.category) return false;
    if (state.trigger && (scenario.trigger || []).indexOf(state.trigger) === -1) return false;
    if (state.autonomy && scenario.autonomy !== state.autonomy) return false;
    if (state.status && scenario.status !== state.status) return false;
    if (state.topPickOnly && !scenario.topPick) return false;
    if (state.query) {
      var haystack = (scenario.title + " " + scenario.summary + " " + (scenario.samplePrompt || "")).toLowerCase();
      if (haystack.indexOf(state.query) === -1) return false;
    }
    return true;
  }

  function triggerLabel(scenario) {
    return (scenario.trigger || []).map(function (t) { return TRIGGER_LABELS[t] || t; }).join(" + ");
  }

  /* ── Rendering ───────────────────────────────────────────────────── */
  function renderCard(scenario) {
    var cat = categoryBySlug[scenario.domain] || { label: scenario.domain, color: "#1A77E3" };
    var card = document.createElement("button");
    card.type = "button";
    card.className = "scenario-card";
    card.style.setProperty("--card-color", cat.color);
    card.setAttribute("data-id", scenario.id);
    card.innerHTML =
      '<div class="scenario-card-top">' +
      '<span class="scenario-card-category">' + escapeHtml(cat.label) + '</span>' +
      (scenario.topPick ? '<span class="scenario-card-star" title="Quick win">★</span>' : "") +
      '</div>' +
      '<div class="scenario-card-title">' + escapeHtml(scenario.title) + '</div>' +
      '<div class="scenario-card-desc">' + escapeHtml(scenario.summary) + '</div>' +
      '<div class="scenario-card-footer">' +
      '<span class="scenario-badge scenario-badge-mode">' + escapeHtml(triggerLabel(scenario)) + '</span>' +
      '<span class="scenario-badge scenario-badge-mode">' + escapeHtml(STATUS_LABELS[scenario.status] || scenario.status) + '</span>' +
      (scenario.timeSaved ? '<span class="scenario-badge ' + timeBadgeClass(scenario.timeSaved) + '">' + escapeHtml(scenario.timeSaved) + ' savings</span>' : "") +
      '</div>';
    card.addEventListener("click", function () { openDrawer(scenario); });
    return card;
  }

  function render() {
    var filtered = SCENARIOS.filter(matches);
    grid.innerHTML = "";
    var frag = document.createDocumentFragment();
    filtered.forEach(function (s) { frag.appendChild(renderCard(s)); });
    grid.appendChild(frag);
    emptyState.hidden = filtered.length !== 0;
    resultsCount.textContent = filtered.length + " of " + SCENARIOS.length + " use cases";
  }

  function bindEvents() {
    /* ── Toolbar events ──────────────────────────────────────────────── */
    var searchDebounce;
    searchInput.addEventListener("input", function () {
      clearTimeout(searchDebounce);
      var val = searchInput.value;
      searchDebounce = setTimeout(function () {
        state.query = val.trim().toLowerCase();
        render();
      }, 120);
    });

    [[triggerFilter, "trigger"], [autonomyFilter, "autonomy"], [statusFilter, "status"]].forEach(function (pair) {
      pair[0].addEventListener("change", function () {
        state[pair[1]] = pair[0].value;
        render();
      });
    });

    topPickToggle.addEventListener("click", function () {
      state.topPickOnly = !state.topPickOnly;
      topPickToggle.classList.toggle("active", state.topPickOnly);
      topPickToggle.setAttribute("aria-pressed", String(state.topPickOnly));
      render();
    });

    chipsContainer.addEventListener("click", function (e) {
      var btn = e.target.closest(".scenario-chip");
      if (!btn) return;
      state.category = btn.dataset.category || "";
      chipsContainer.querySelectorAll(".scenario-chip").forEach(function (c) {
        c.classList.toggle("active", c === btn);
      });
      render();
    });
  }

  /* ── Detail drawer ───────────────────────────────────────────────── */
  var drawer = document.getElementById("scenario-drawer");
  var drawerOverlay = document.getElementById("scenario-drawer-overlay");
  var drawerCategory = document.getElementById("scenario-drawer-category");
  var drawerTitle = document.getElementById("scenario-drawer-title");
  var drawerBadges = document.getElementById("scenario-drawer-badges");
  var drawerDesc = document.getElementById("scenario-drawer-desc");
  var drawerPrompt = document.getElementById("scenario-drawer-prompt");
  var drawerFrequency = document.getElementById("scenario-drawer-frequency");
  var drawerClose = document.getElementById("scenario-drawer-close");
  var promptBlock = document.getElementById("scenario-prompt-block");
  var drawerComponents = document.getElementById("scenario-drawer-components");
  var drawerProducts = document.getElementById("scenario-drawer-products");
  var drawerGithub = document.getElementById("scenario-drawer-github");
  var copyBtn = document.getElementById("scenario-copy-btn");
  var drawerActions = document.getElementById("scenario-drawer-actions");
  var drawerPage = document.getElementById("scenario-drawer-page");
  var drawerDownload = document.getElementById("scenario-drawer-download");
  var currentScenario = null;

  function openDrawer(scenario) {
    currentScenario = scenario;
    var cat = categoryBySlug[scenario.domain] || { label: scenario.domain };
    drawerCategory.textContent = cat.label;
    drawerTitle.textContent = scenario.title;
    drawerDesc.textContent = scenario.summary;
    drawerPrompt.textContent = scenario.samplePrompt || "";
    promptBlock.hidden = !scenario.samplePrompt || scenario.status !== "idea";
    drawerFrequency.textContent = scenario.frequency || "—";
    drawerBadges.innerHTML =
      (scenario.topPick ? '<span class="scenario-badge scenario-card-star" style="color:#b45309;border-color:rgba(180,83,9,.3);background:rgba(180,83,9,.08);">★ Quick win</span>' : "") +
      '<span class="scenario-badge scenario-badge-mode">' + escapeHtml(triggerLabel(scenario)) + '</span>' +
      '<span class="scenario-badge scenario-badge-mode">' + escapeHtml(STATUS_LABELS[scenario.status] || scenario.status) + '</span>' +
      (scenario.autonomy ? '<span class="scenario-badge scenario-badge-mode">' + escapeHtml(AUTONOMY_LABELS[scenario.autonomy] || scenario.autonomy) + '</span>' : "") +
      (scenario.timeSaved ? '<span class="scenario-badge ' + timeBadgeClass(scenario.timeSaved) + '">' + escapeHtml(scenario.timeSaved) + ' time savings</span>' : "");
    renderComponents(scenario);
    drawerActions.hidden = !scenario.page;
    if (scenario.page) {
      drawerPage.href = "usecase.html?id=" + encodeURIComponent(scenario.id);
      drawerDownload.hidden = !scenario.download;
      if (scenario.download) drawerDownload.href = scenario.download.url;
    }
    copyBtn.textContent = "Copy prompt";
    copyBtn.classList.remove("copied");
    drawer.classList.add("open");
    drawerOverlay.classList.add("open");
    drawer.querySelector(".drawer-body").scrollTop = 0;
  }

  function renderComponents(scenario) {
    var c = scenario.components || {};
    var present = COMPONENT_LABELS.filter(function (pair) { return c[pair[0]]; });
    drawerComponents.innerHTML = present.length
      ? present.map(function (pair) { return "<li>" + escapeHtml(pair[1]) + "</li>"; }).join("")
      : "<li>—</li>";
    drawerComponents.classList.toggle("is-empty", !present.length);
    drawerProducts.textContent = (scenario.products || []).join(", ") || "—";
    drawerGithub.href = REPO_TREE + scenario.path;
  }

  function closeDrawer() {
    drawer.classList.remove("open");
    drawerOverlay.classList.remove("open");
  }

  drawerClose.addEventListener("click", closeDrawer);
  drawerOverlay.addEventListener("click", closeDrawer);
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape" && drawer.classList.contains("open")) closeDrawer();
  });

  copyBtn.addEventListener("click", function () {
    if (!currentScenario) return;
    var text = currentScenario.samplePrompt || "";
    function markCopied() {
      copyBtn.textContent = "Copied ✓";
      copyBtn.classList.add("copied");
      setTimeout(function () {
        copyBtn.textContent = "Copy prompt";
        copyBtn.classList.remove("copied");
      }, 1800);
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(markCopied).catch(function () {
        fallbackCopy(text, markCopied);
      });
    } else {
      fallbackCopy(text, markCopied);
    }
  });

  function fallbackCopy(text, onDone) {
    var ta = document.createElement("textarea");
    ta.value = text;
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    try { document.execCommand("copy"); } catch (err) { /* no-op */ }
    document.body.removeChild(ta);
    onDone();
  }
})();
